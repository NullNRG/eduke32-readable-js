import assert from 'node:assert/strict';
import { LLVMContext } from '../runtime/llvm_context.mjs';
const c=new LLVMContext();
assert.deepEqual(c.x86DivRem(64,100n,0n,7n),[14n,2n]);
assert.deepEqual(c.x86DivRem(32,-1,0,10),[429496729,5]);
assert.throws(()=>c.x86DivRem(64,100n,0n,0n),/divide-by-zero/);
assert.throws(()=>c.x86DivRem(64,0n,1n,1n),/overflow/);
assert.deepEqual(c.aggregateInsert([undefined,undefined],17n,0,2),[17n,undefined]);
assert.equal(c.aggregateExtract([17n,undefined],0,2),17n);
assert.throws(()=>c.aggregateExtract([17n,undefined],1,2),/poison\/undef/);
assert.equal(c.vectorBinary('xor',[12n,-1n],[10n,1n],2,'i64')[0],6n);
assert.equal(c.reinterpretVectorBits('double',c.reinterpretVectorBits('<2 x float>',[1.25,2.5],'double'),'<2 x float>')[0],1.25);
assert.equal(c.libraries['llvm.ctpop.i32'](-1),32);
assert.equal(c.libraries['llvm.cttz.i32'](8,1),3);
assert.equal(c.libraries['llvm.bitreverse.i32'](1),-2147483648);
assert.deepEqual(c.libraries['llvm.sadd.with.overflow.i32'](2147483647,1),[-2147483648,1]);
assert.deepEqual(c.libraries['llvm.umul.with.overflow.i64']((1n<<64n)-1n,2n),[-2n,1]);
assert.equal(c.libraries['llvm.fshl.i64'](1n,2n,1n),2n);
assert.equal(c.libraries['llvm.threadlocal.address.p0'](1234),1234);
c.atomicFence('seq_cst');
c.assumeAlignment(48,16);
assert.throws(()=>c.assumeAlignment(49,16),/alignment/);
const mem=c.heap.malloc(16);
c.store(mem,'i128',(1n<<120n)+51n);
assert.equal(c.load(mem,'i128'),(1n<<120n)+51n);
assert.throws(()=>c.libraries['llvm.trap'](),/trap/);
console.log('PASS: dedup runtime primitives');
