#!/usr/bin/env python3
"""Trace exact original startup source dependencies against a selected build snapshot.

Manifests are historical evidence until regenerated by a fresh, cold compile;
this tool never promotes a block to an executable source export.
"""
import argparse
from collections import Counter,defaultdict
from pathlib import Path
import json,hashlib,sys
ROOT=Path(__file__).resolve().parents[1]

def build(source_root,entry='app_main'):
    source_root=Path(source_root)
    manifests=list(sorted(source_root.rglob('*.manifest.json')))
    if not manifests:raise RuntimeError('No original-source manifests in '+str(source_root))
    # Normalize duplicates caused by multiple clang observations of the same
    # header declaration inside one original translation unit.
    definitions=defaultdict(dict)
    module_digests={}
    for path in manifests:
        doc=json.loads(path.read_text())
        owner=doc.get('source')
        if not owner:continue
        module_digests[owner]=hashlib.sha256(path.read_bytes()).hexdigest()
        for row in doc.get('definitions',[]):
            if row.get('kind') not in ('FunctionDecl','VarDecl','CXXRecordDecl'):continue
            if row.get('status') not in ('source-first','blocked'):continue
            name=row.get('name')
            if not name:continue
            key=(name,row.get('kind'),row.get('original_type'))
            previous=definitions[owner].get(key)
            if previous is None or (previous['status']=='blocked' and row['status']=='source-first'):
                definitions[owner][key]=row
    owners=defaultdict(list)
    for unit,by_identity in definitions.items():
        for identity,definition in by_identity.items():
            owners[identity[0]].append((unit,definition))
    entry_owners=owners.get(entry,[])
    if len(entry_owners)!=1:raise RuntimeError('Missing/ambiguous startup entry declaration')
    source,entry_definition=entry_owners[0]
    refs=sorted(set(entry_definition.get('unresolved_references') or []))
    rows=[]
    for name in refs:
        matches=owners.get(name,[])
        # Treat ambiguous declarations conservatively, including different
        # source owners. No silently selected arbitrary source owner.
        emitted=[(unit,d) for unit,d in matches if d['status']=='source-first']
        status=('no-proven-provider' if not matches else
                'ambiguous-source-owners' if len({unit for unit,_ in emitted})>1 else
                'emitted-in-snapshot' if emitted else 'source-semantics-blocked')
        rows.append({'name':name,'status':status,'providers':[
            {'source':unit,'status':d['status'],'reason':d.get('reason')} for unit,d in matches[:8]]})
    counts=Counter(row['status'] for row in rows)
    return {'format':'source-first-boot-symbol-frontier/1','manifest_root':str(source_root.relative_to(ROOT)) if source_root.is_relative_to(ROOT) else str(source_root),
      'status':'INCOMPLETE','snapshot_freshly_recompiled':False,
      'selected_source_manifests':len(module_digests),
      'selected_entry_source':source,'entry':entry,
      'entry_status':entry_definition['status'],'entry_reason':entry_definition.get('reason'),
      'original_gameplay_verified':False,'entry_unresolved_references':len(refs),
      'by_provider_state':dict(sorted(counts.items())),
      'missing_symbols':rows,'source_manifest_sha256':module_digests[source]}

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',type=Path,default=ROOT/'factory-output/source-first/force-recovered')
    p.add_argument('--out',type=Path,default=ROOT/'reports/startup/original-boot-frontier.json')
    args=p.parse_args()
    result=build(args.root.resolve())
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({key:result[key] for key in ('status','selected_source_manifests','entry','entry_status','entry_unresolved_references','by_provider_state')},indent=2))
    return 0
if __name__=='__main__':sys.exit(main())
