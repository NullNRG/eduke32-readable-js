"""Export the verified original-engine probe as an asset-free browser runner.

Reuse the existing transformations, stopping before browser execution/report
writes. The generated runner takes user-selected archive bytes and MAP name.
"""
import ast,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def build():
    path=ROOT/'work/verify_original_masked_frame.py';tree=ast.parse(path.read_text())
    arguments=sys.argv[:]
    try:
        sys.argv=['engine-launcher-generation']
        for _ in range(4):
            stop=next(i for i,node in enumerate(tree.body) if isinstance(node,ast.Try))
            prefix=ast.Module(body=tree.body[:stop],type_ignores=[])
            scope={'__file__':str(path),'__name__':'engine_launcher_extraction'}
            exec(compile(ast.fix_missing_locations(prefix),str(path),'exec'),scope)
            tree=scope['tree']
            path=scope.get('source') or scope.get('probe') or scope.get('path')
        blocks=[n.value for n in ast.walk(tree) if isinstance(n,ast.Constant) and isinstance(n.value,str)
                and n.value.startswith('async ({base,consoleOnly})=>')]
        assert len(blocks)==1
        script=blocks[0]
    finally:sys.argv=arguments
    def replace(before,after):
        nonlocal script
        if script.count(before)!=1:raise ValueError('Verified engine probe changed: '+before)
        script=script.replace(before,after,1)
    replace('async ({base,consoleOnly})=>','async ({base,archiveBytes,mapName,consoleOnly=false})=>')
    replace("const response=await fetch('/input-data/DUKE3D.GRP');if(!response.ok)throw Error('Supplied GRP unavailable');\n      const archive=new Uint8Array(await response.arrayBuffer());",
            "if(!(archiveBytes instanceof ArrayBuffer))throw Error('Select a GRP first');\n      const archive=new Uint8Array(archiveBytes);")
    replace('vfs.gnumfiles[0]!==456',"vfs.gnumfiles[0]!==new DataView(archive.buffer).getUint32(12,true)")
    replace('const selectedMaps=["E1L1.MAP"];','const selectedMaps=[mapName];')
    profile=json.loads((ROOT/'tools/browser_classic_profile.json').read_text())
    output=ROOT/'engine-level-runner.mjs'
    output.write_text('// Generated by tools/build_engine_launcher.py from the verified original engine probe.\n'
        '// Engine component only: app_main/CON/gameplay are not implemented here.\n'
        +'export const moduleBase='+json.dumps('/'+profile['boot_module_root'])+';\nexport default '+
        '\n'.join(line.rstrip() for line in script.splitlines())+';\n',encoding='utf-8',newline='\n')
    return output

if __name__=='__main__':print(build())
