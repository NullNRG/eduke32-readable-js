#!/usr/bin/env python3
"""Audit actual emitted JavaScript before calling a startup symbol missing.

A historical Clang declaration does not prove that JavaScript was emitted.
No providers or stubs are generated by this tool.
"""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
INDEX=ROOT/'reports/browser-target/combined-closure.json'
OUT=ROOT/'reports/browser-target/historical-ast-gap.json'
EXPORT=re.compile(r'^export\s+(?:(?:async)\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)\b',re.M)
def main():
 j=json.loads(INDEX.read_text());all_missing=j['app_main_direct_still_unprovided']
 active=ROOT/'factory-output/source-first/browser-target/source'
 history=ROOT/'factory-output/source-first'
 target=set(all_missing)
 actual={name:[] for name in all_missing}
 for path in history.rglob('*.mjs'):
  if '/browser-abi/' in path.as_posix():continue
  found=set(EXPORT.findall(path.read_text(encoding='utf8'))) & target
  for name in found:actual[name].append(str(path.relative_to(ROOT)))
 manifests={name:[] for name in all_missing}
 snapshot=ROOT/'factory-output/source-first/force-recovered'
 for path in snapshot.rglob('*.manifest.json'):
  doc=json.loads(path.read_text());owner=doc.get('source')
  for row in doc.get('definitions',[]):
   if row.get('name') in manifests:
    manifests[row['name']].append({'owner':owner,'status':row.get('status'),'reason':row.get('reason','')})
 details=[{'name':name,'historical_emitted_paths':actual[name],
    'historically_emitted':bool(actual[name]),'snapshot_manifest':manifests[name]} for name in all_missing]
 out={'format':'eduke32-ast-gap-audit/1','snapshot_direct_unprovided':len(all_missing),
    'found_actual_historical_js_exports':sum(bool(x['historical_emitted_paths']) for x in details),
    'no_historical_js_export':sum(not x['historical_emitted_paths'] for x in details),
    'symbols':details,'note':'Past AST declarations are not executable JS exports; generated classes from different source units may not be compatible/linkable.',
    'originalGameplayVerified':False}
 OUT.parent.mkdir(parents=True,exist_ok=True);OUT.write_text(json.dumps(out,indent=2)+'\n')
 print(json.dumps({k:v for k,v in out.items() if k not in ('symbols','note')},indent=2))
if __name__=='__main__':main()
